/* =====================================================================
   예제 회로 (교과서 단원 흐름에 맞춘 학습 활동)
   ===================================================================== */
function add(type, x, y, rot, props) { const c = newComp(type, x, y, props); c.rot = rot || 0; return c; }
function wire(x1, y1, x2, y2) { const c = newComp('wire', (x1 + x2) / 2, (y1 + y2) / 2); c.a = { x: x1, y: y1 }; c.b = { x: x2, y: y2 }; return c; }
function poly(pts) { for (let i = 0; i < pts.length - 1; i++) if (Math.hypot(pts[i + 1][0] - pts[i][0], pts[i + 1][1] - pts[i][1]) > 0.5) wire(pts[i][0], pts[i][1], pts[i + 1][0], pts[i + 1][1]); }
/* 계기의 단자 k에서 바깥쪽으로 나온 뒤 직각으로 꺾어 점 E에 닿는 전선 */
function wireOut(c, k, E, d) {
  d = d || 30;
  const T = tpos(c, k), a = c.rot * PI / 180, ox = -Math.sin(a), oy = Math.cos(a);
  const t0 = [Math.round(T.x), Math.round(T.y)], t2 = [Math.round(T.x + ox * d), Math.round(T.y + oy * d)];
  poly([t0, t2, Math.abs(oy) > 0.5 ? [E[0], t2[1]] : [t2[0], E[1]], E]);
}
function meterV(x, y, pa, pb) { const c = newComp('voltmeter', x, y); c.pa = { x: pa[0], y: pa[1] }; c.pb = { x: pb[0], y: pb[1] }; c.pc = { x: x + 98, y: y + 62 }; return c; }

/* 기본 직사각형 회로의 공통 부분 */
function baseLoop(o) {
  o = o || {};
  add('battery', 0, 110, 0, { V: o.V || 10 });
  add('bulb', 0, -110, 0);
  add('switch', 200, 0, 90, { closed: o.closed !== false });
  poly([[-70, 110], [-200, 110], [-200, -110], [-60, -110]]);
  poly([[60, -110], [200, -110], [200, -50]]);
  poly([[200, 50], [200, 110], [70, 110]]);
}

